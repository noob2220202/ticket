function run() {
  if (ACCOUNT_INFO.length !== 35) {
    console.error(`예상한 행 수(35)와 다릅니다: ${ACCOUNT_INFO.length}행.`);
    process.exit(1);
  }

  const seqByStamp = {};
  const update = dbMod.db.prepare('UPDATE payouts SET account_info = ? WHERE id = ?');

  let updated = 0;
  let missing = 0;

  ACCOUNT_INFO.forEach(([date, time, name, accountInfo]) => {
    const stampKey = `${date.replace(/-/g, '')}${time.replace(/:/g, '')}`;
    seqByStamp[stampKey] = (seqByStamp[stampKey] || 0) + 1;
    const seq = seqByStamp[stampKey];
    const payoutId = `MIG-${stampKey}-${seq}`;

    const result = update.run(accountInfo, payoutId);
    if (result.changes > 0) updated += 1; else { missing += 1; console.warn('매칭 안 됨:', payoutId, name, accountInfo); }
  });

  console.log(`업데이트: ${updated}건`);
  if (missing) console.log(`매칭 실패: ${missing}건`);
  console.log('완료.');
}

run();
