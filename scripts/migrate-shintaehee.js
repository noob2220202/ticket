function parseDeposits(raw) {
  const out = [];
  raw.split('\n').forEach((line) => {
    const m = line.trim().match(/^(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})\s+([\d,]+)$/);
    if (!m) return;
    out.push({ when: m[1], amount: Number(m[2].replace(/,/g, '')) });
  });
  return out;
}

// KST(한국시간, UTC+9) 기준 "YYYY-MM-DD HH:mm:ss" 문자열을 UTC ISO 문자열로 변환.
function kstToIso(when) {
  return new Date(`${when.replace(' ', 'T')}+09:00`).toISOString();
}

function roundToUnit(amount, unit) {
  return Math.round(amount / unit) * unit;
}

function breakdown(amount) {
  let remaining = amount;
  const items = [];
  for (const denom of DENOMS) {
    const qty = Math.floor(remaining / denom);
    if (qty > 0) {
      items.push({ denom, qty });
      remaining -= qty * denom;
    }
  }
  if (remaining !== 0) {
    throw new Error(`금액 ${amount}을 주어진 액면으로 정확히 나눌 수 없습니다(나머지 ${remaining}).`);
  }
  return items;
}

function makePinGenerator(usedPins) {
  const prefixes = ['9001', '9002', '9003', '9004', '9005', '9006', '9007', '9008', '9009'];
  return function generatePin() {
    let pin;
    do {
      const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
      let rest = '';
      for (let i = 0; i < 12; i += 1) rest += Math.floor(Math.random() * 10);
      pin = prefix + rest;
    } while (usedPins.has(pin));
    usedPins.add(pin);
    return pin;
  };
}

function run() {
  const deposits = parseDeposits(DEPOSITS_RAW);
  if (!deposits.length) {
    console.error('파싱된 입금 내역이 없습니다. DEPOSITS_RAW 포맷을 확인하세요.');
    process.exit(1);
  }

  const already = dbMod.listPayouts().filter((p) => (p.orderNo || '').startsWith('MIG-'));
  if (already.length) {
    console.error(
      `이미 이 스크립트로 이전된 지급내역이 ${already.length}건 있습니다. ` +
      `중복 삽입을 막기 위해 중단합니다. 다시 실행해야 한다면 기존 MIG- 데이터를 먼저 정리하세요.`
    );
    process.exit(1);
  }

  const usedPins = new Set(dbMod.existingPins());
  const generatePin = makePinGenerator(usedPins);

  let totalDeposit = 0;
  let totalPayout = 0;
  let rowCount = 0;

  // 같은 초(timestamp)에 여러 건이 있을 수 있어 순번을 붙여 order_no/id를 구분합니다.
  const seqByStamp = {};

  deposits.forEach((d) => {
    const createdAt = kstToIso(d.when);
    const stampKey = d.when.replace(/[-: ]/g, '');
    seqByStamp[stampKey] = (seqByStamp[stampKey] || 0) + 1;
    const seq = seqByStamp[stampKey];

    const payoutAmount = roundToUnit(d.amount * (1 + FEE_RATE), 10000);
    const items = breakdown(payoutAmount);
    const orderNo = `MIG-${stampKey}-${seq}`;
    const memo =
      `구 사이트 지급내역 이전 · 입금액 ${d.amount.toLocaleString('ko-KR')}원 + 3% = ` +
      `${payoutAmount.toLocaleString('ko-KR')}원`;

    items.forEach((item, idx) => {
      const id = `PO-${stampKey}-${seq}-${idx + 1}`;
      const pins = Array.from({ length: item.qty }, () => generatePin());

      dbMod.insertPayout({
        id,
        orderNo,
        createdAt,
        customer: { name: CUSTOMER_NAME },
        brand: BRAND,
        brandName: BRAND_NAME,
        denom: item.denom,
        qty: item.qty,
        pins,
        memo,
        source: 'migration',
      });
      rowCount += 1;
    });

    totalDeposit += d.amount;
    totalPayout += payoutAmount;
  });

  console.log(`입금 건수: ${deposits.length}건`);
  console.log(`생성된 지급내역 행(액면별): ${rowCount}행`);
  console.log(`입금 총액: ${totalDeposit.toLocaleString('ko-KR')}원`);
  console.log(`지급(상품권) 총액: ${totalPayout.toLocaleString('ko-KR')}원`);
  console.log('완료.');
}

run();
